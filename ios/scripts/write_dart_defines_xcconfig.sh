#!/bin/bash
# Xcode scheme pre-action: Flutter가 넘긴 DART_DEFINES(base64, 쉼표 구분) 중
# 네이티브 설정에 필요한 값만 Flutter/DartDefines.xcconfig로 풀어 쓴다.
# Info.plist의 $(KAKAO_NATIVE_APP_KEY)가 이 값을 읽는다.
set -euo pipefail

OUT="${SRCROOT}/Flutter/DartDefines.xcconfig"
echo "// Generated by ios/scripts/write_dart_defines_xcconfig.sh. Do not edit." > "$OUT"

IFS=',' read -r -a defines <<< "${DART_DEFINES:-}"
for encoded in "${defines[@]}"; do
  [ -z "$encoded" ] && continue
  decoded=$(echo "$encoded" | base64 --decode)
  case "$decoded" in
    FLAVOR=*|KAKAO_NATIVE_APP_KEY=*) echo "$decoded" >> "$OUT" ;;
  esac
done
